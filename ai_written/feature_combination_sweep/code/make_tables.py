#!/usr/bin/env python3
"""
make_tables.py -- thesis-ready LaTeX tables (plain tabular + \\hline, no extra package) from tables/sweep_metrics.csv.
Every number is read from that file; nothing is typed.

  python make_tables.py --metrics ../tables/sweep_metrics.csv --out ../tables

  ttp_vs_3f_6f.tex        every method and hybrid: TTP-only against the thesis' three- and six-feature tools
                          (sanity check Top-1, stress test Top-1 and Top-5, CTI score on the 27 reports with TTPs)
  sweep_all_combinations.tex      the 63 combinations x every approach and hybrid: stress-test Top-1
  sweep_all_combinations_cti.tex  the 32 combinations with TTPs x every approach and hybrid: CTI score (27 reports)
  sweep_family_effect.tex median change of the stress-test Top-1 when a feature type is added (31 pairs per type)
  *_thesis_layout.tex     TTP-only, 6f and 3f in the LaTeX of the thesis' Tables 4.5 / 4.6
  ttp_evidence_6f_thesis_layout.tex, ttp_evidence_3f_thesis_layout.tex
                          the thesis' 6f and 3f tools unchanged (saved models), queries with TTPs only
                          (run_ttp_evidence.sh), same LaTeX
"""
import os
import csv
import argparse
from collections import defaultdict

import numpy as np

FAMILIES = ['techniques', 'software', 'capec', 'cwe', 'cve', 'pulse']
FAM_LABEL = {'techniques': 'TTPs', 'software': 'Software', 'capec': 'CAPEC', 'cwe': 'CWE', 'cve': 'CVE', 'pulse': 'Pulse'}
LETTER = {'techniques': 'T', 'software': 'S', 'capec': 'A', 'cwe': 'W', 'cve': 'V', 'pulse': 'P'}
METHOD_LABEL = {'xgboost': 'XGBoost', 'gnn': 'GNN', 'siamese': 'Siamese', 'mil': 'MIL', 'rf': 'Random Forest',
                'jaccard': 'Jaccard', 'tvd': 'TVD', 'featureMatching': 'Feature Matching',
                'hybrid_no_weights': 'Hybrid, no weights', 'hybrid_self_eval_weights': 'Hybrid, self-eval weights',
                'hybrid_CTI_boosting': 'Hybrid, CTI boosting'}
ALL_METHODS = ['xgboost', 'gnn', 'siamese', 'mil', 'rf', 'jaccard', 'tvd', 'featureMatching',
               'hybrid_no_weights', 'hybrid_self_eval_weights', 'hybrid_CTI_boosting']
FOUR = ['jaccard', 'featureMatching', 'tvd', 'rf']


def read(path):
    data = defaultdict(dict)
    with open(path) as fh:
        for r in csv.DictReader(fh):
            for k in ('top1', 'top5', 'top10', 'top20', 'mean_rank', 'cti_score'):
                r[k] = float(r[k]) if r.get(k) not in (None, '', 'None') else np.nan
            data[(r['source'], r['config'], r['method'])][r['evaluation']] = r
    return data


def val(data, src, cfg, m, ev, field):
    r = data.get((src, cfg, m), {}).get(ev)
    return np.nan if r is None else r[field]


def n_of(data, src, cfg, m, ev):
    """number of queries (groups or CTI reports) behind an evaluation, or None"""
    r = data.get((src, cfg, m), {}).get(ev)
    try:
        return int(float(r['n']))
    except Exception:
        return None


def fmt(v, nd=1):
    return '--' if v is None or (isinstance(v, float) and np.isnan(v)) else f'{v:.{nd}f}'


def write(path, lines):
    with open(path, 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    print(f"[tables] {os.path.basename(path)}")


def table_ttp(data, ttp_src, out):
    cols = [('sanity', 'top1'), ('stress', 'top1'), ('stress', 'top5'), ('cti_ttp', 'cti_score')]
    tools = [(ttp_src, 'T'), ('thesis3f', 'TSV'), ('thesis6f', 'TSAWVP')]
    lines = ['% generated by make_tables.py from sweep_metrics.csv -- do not edit by hand',
             '% TTP-only = the six-feature tool retrained on data with every non-TTP feature type blanked (-1);',
             '% 3f / 6f = the thesis tools (their saved results). CTI = mean CTI score on the 27 CTI reports that contain TTPs.',
             '\\begin{tabular}{l|ccc|ccc|ccc|ccc}', '\\hline',
             ' & \\multicolumn{3}{c|}{Sanity check Top-1 (\\%)} & \\multicolumn{3}{c|}{Stress test Top-1 (\\%)} & '
             '\\multicolumn{3}{c|}{Stress test Top-5 (\\%)} & \\multicolumn{3}{c}{CTI score (27 reports)} \\\\',
             'Method & TTP & 3f & 6f & TTP & 3f & 6f & TTP & 3f & 6f & TTP & 3f & 6f \\\\', '\\hline']
    for m in ALL_METHODS:
        if m.startswith('hybrid') and m == 'hybrid_no_weights':
            lines.append('\\hline')
        cells = []
        for ev, field in cols:
            for src, cfg in tools:
                cells.append(fmt(val(data, src, cfg, m, ev, field), 2 if ev.startswith('cti') else 1))
        lines.append(f"{METHOD_LABEL[m]} & " + ' & '.join(cells) + ' \\\\')
    lines += ['\\hline', '\\end{tabular}']
    write(os.path.join(out, 'ttp_vs_3f_6f.tex'), lines)


EIGHT = ['xgboost', 'gnn', 'siamese', 'mil', 'rf', 'featureMatching', 'jaccard', 'tvd']     # the thesis tables' order
HYBRIDS = ['hybrid_no_weights', 'hybrid_self_eval_weights', 'hybrid_CTI_boosting']
SHORT = {'xgboost': 'XGB', 'gnn': 'GNN', 'siamese': 'Siam.', 'mil': 'MIL', 'rf': 'RF', 'featureMatching': 'FM',
         'jaccard': 'Jacc.', 'tvd': 'TVD', 'hybrid_no_weights': 'H-none', 'hybrid_self_eval_weights': 'H-self',
         'hybrid_CTI_boosting': 'H-CTI'}


def approaches(data, src):
    have = {m for s, _, m in data if s == src}
    return [m for m in EIGHT + HYBRIDS if m in have]


def table_sweep(data, src, out):
    """Every combination x every approach: stress-test Top-1 (all 63) and CTI score (the 32 with TTPs)."""
    keys = sorted({k for (s, k, m) in data if s == src}, key=lambda k: (len(k), ['TSAWVP'.index(c) for c in k]))
    meths = approaches(data, src)
    for ev, field, name, rows, what in (
            ('stress', 'top1', 'sweep_all_combinations.tex', keys, 'stress-test (shuffled and divided) Top-1, in %'),
            ('cti_ttp', 'cti_score', 'sweep_all_combinations_cti.tex', [k for k in keys if 'T' in k],
             'CTI score on the 27 CTI reports that contain TTPs (combinations with TTPs only)')):
        lines = ['% generated by make_tables.py from sweep_metrics.csv -- do not edit by hand',
                 f'% {what}. Combination letters: T TTPs, S software, A CAPEC, W CWE, V CVE, P Pulse.',
                 '% XGB, GNN, Siamese, MIL, RF retrained per combination (one training); H- = the three WRRF hybrids;',
                 '% "--" = not run yet.',
                 '{\\scriptsize\\setlength{\\tabcolsep}{2.5pt}',
                 '\\begin{tabular}{l|' + 'c' * len([m for m in meths if m in EIGHT[:5]]) + '|' +
                 'c' * len([m for m in meths if m in EIGHT[5:]]) +
                 ('|' + 'c' * len([m for m in meths if m in HYBRIDS]) if any(m in HYBRIDS for m in meths) else '') + '}',
                 '\\hline', 'Combination & ' + ' & '.join(SHORT[m] for m in meths) + ' \\\\', '\\hline']
        prev = None
        for k in rows:
            if prev is not None and len(k) != len(prev):
                lines.append('\\hline')
            lines.append(f"{k} & " + ' & '.join(fmt(val(data, src, k, m, ev, field)) for m in meths) + ' \\\\')
            prev = k
        lines += ['\\hline', '\\end{tabular}}']
        write(os.path.join(out, name), lines)


def family_effects(data, src, methods, ev='stress', field='top1'):
    vals = {(m, k): r[ev][field] for (s, k, m), r in data.items() if s == src and ev in r}
    out = {}
    for m in methods:
        for f in FAMILIES:
            d = []
            for (mm, k), v in vals.items():
                if mm != m or LETTER[f] in k:
                    continue
                plus = ''.join(c for c in 'TSAWVP' if c in k + LETTER[f])
                if (m, plus) in vals and not np.isnan(v) and not np.isnan(vals[(m, plus)]):
                    d.append(vals[(m, plus)] - v)
            if d:
                out[(m, f)] = (float(np.median(d)), float(np.min(d)), float(np.max(d)), len(d))
    return out


def table_family(data, src, out):
    meths = approaches(data, src)
    eff = family_effects(data, src, meths)
    lines = ['% generated by make_tables.py from sweep_metrics.csv -- do not edit by hand',
             '% Change of the stress-test Top-1 (percentage points) when the feature type is added to a combination',
             '% that does not have it: median [minimum, maximum] over the 31 such pairs (fewer while the Mac sweep runs).',
             '{\\small', '\\begin{tabular}{l|' + 'c' * len(FAMILIES) + '}', '\\hline',
             'Approach & ' + ' & '.join(FAM_LABEL[f] for f in FAMILIES) + ' \\\\', '\\hline']
    for m in meths:
        cells = []
        for f in FAMILIES:
            if (m, f) in eff:
                med, lo, hi, n = eff[(m, f)]
                cells.append(f'{med:+.1f} [{lo:+.0f}, {hi:+.0f}]' + ('' if n == 31 else f' (n={n})'))
            else:
                cells.append('--')
        lines.append(f'{METHOD_LABEL[m]} & ' + ' & '.join(cells) + ' \\\\')
    lines += ['\\hline', '\\end{tabular}}']
    write(os.path.join(out, 'sweep_family_effect.tex'), lines)
    return eff


def table_thesis_layout(data, src, cfg, out, name, caption, label, note='', what=''):
    """One configuration in the LaTeX of the thesis' Tables 4.5 and 4.6 (same environment, column format, rules,
    \\multirow blocks and spacer rows, so it sits next to them unchanged): methods as columns; sanity check and stress
    test Top-1/5/10/20; CTI ranking score.  Two CTI rows: the 27 reports that contain TTPs (the same reports for the
    TTP-only, three- and six-feature tools) and all the reports (the thesis' row; a report with no usable item counts at
    chance, 50%).  Needs \\usepackage{float, multirow, graphicx}, as the thesis already does.  what: one comment line
    saying what was run (written at the top of the file)."""
    ml = ['xgboost', 'gnn', 'siamese', 'mil', 'rf']
    maths = ['featureMatching', 'jaccard', 'tvd']
    cols = ml + maths
    I = ' ' * 6

    def pc(x):
        return '--' if np.isnan(x) else f'{x:.2f}\\%'

    def row(lab, values, end):
        return f'{I}& {lab} & ' + ' & '.join(values[:5]) + f'\n{I}    & ' + ' & '.join(values[5:]) + f' \\\\ {end}'

    lines = ['% generated by make_tables.py from tables/sweep_metrics.csv -- do not edit by hand',
             f'% configuration {cfg} (source "{src}"), written in the LaTeX of the thesis Tables 4.5 and 4.6'] + \
            ([f'% {w}' for w in what.split('\n')] if what else []) + \
            ['\\begin{table}[H]', '  \\centering',
             f'  \\caption{{{caption}' + (f' {note}' if note else '') + '}', f'  \\label{{{label}}}',
             '  \\resizebox{\\textwidth}{!}{%', '    \\footnotesize', '    \\renewcommand{\\arraystretch}{0.80}',
             '    \\begin{tabular}{|l|l|*{8}{c|}}', f'{I}\\hline',
             f'{I}\\multicolumn{{1}}{{|c|}}{{}} & \\multicolumn{{1}}{{c|}}{{}} &',
             f'{I}\\multicolumn{{5}}{{c|}}{{ML models}} &', f'{I}\\multicolumn{{3}}{{c|}}{{Mathematical algorithm}} \\\\',
             f'{I}\\hline', f'{I}& top', f'{I}& XGboost & GNN & Siamese & MIL & RF',
             f"{I}& Feature Matching & Jaccard's & TVD \\\\", f'{I}\\hline']
    spacer = f'{I}& & & & & & & & & \\\\ \\hline'
    for ev, title in (('sanity', 'Sanity Check'), ('stress', 'Stress testing - Shuffled and Divided')):
        lines.append(f'{I}\\multirow{{4}}{{*}}{{{title}}}')
        for i, k in enumerate((1, 5, 10, 20)):
            vals = [pc(val(data, src, cfg, m, ev, f'top{k}')) for m in cols]
            lines.append(row(f'{k:<2d}', vals, '\\hline' if k == 20 else '\\cline{2-10}'))
        lines.append(spacer)
    lines.append(f'{I}\\multirow{{2}}{{*}}{{CTI Ranking Score}}')
    n_ttp, n_all = n_of(data, src, cfg, cols[0], 'cti_ttp'), n_of(data, src, cfg, cols[0], 'cti30')   # counted, not fixed
    lines.append(row(f'{n_ttp} reports with TTPs' if n_ttp else 'reports with TTPs',
                     [pc(val(data, src, cfg, m, 'cti_ttp', 'cti_score')) for m in cols],
                     '\\cline{2-10}'))
    lines.append(row(f'all {n_all} reports' if n_all else 'all reports',
                     [pc(val(data, src, cfg, m, 'cti30', 'cti_score')) for m in cols], '\\hline'))
    lines += ['    \\end{tabular}%%', '  }', '\\end{table}']
    write(os.path.join(out, name), lines)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--metrics', default=os.path.join(here, '..', 'tables', 'sweep_metrics.csv'))
    ap.add_argument('--out', default=os.path.join(here, '..', 'tables'))
    ap.add_argument('--sweep-source', default='sweep')
    ap.add_argument('--ttp-source', default='mac')
    a = ap.parse_args()
    data = read(a.metrics)
    os.makedirs(a.out, exist_ok=True)
    sw = a.sweep_source if any(s == a.sweep_source for s, _, _ in data) else 'cloud'
    ttp_src = a.ttp_source if any(s == a.ttp_source and k == 'T' for s, k, _ in data) else sw
    table_ttp(data, ttp_src, a.out)
    table_sweep(data, sw, a.out)
    table_family(data, sw, a.out)
    # the TTP-only CONFIGURATION: approaches built and queried on TTPs only (combination T of the sweep, first training)
    table_thesis_layout(data, ttp_src, 'T', a.out, 'ttp_only_thesis_layout.tex',
                        'Complete attribution performance using the TTP-only configuration.',
                        'tab:TTPs_config_attribution_no_hybrid_weights',
                        what='the TTP-only configuration: every other feature type set to missing in the data, the ML models '
                             'retrained on it (first of three trainings),\nand every query restricted to its TTPs. The CTI '
                             'reports without TTPs count at chance (50%) in the "all reports" row.')
    if any(s == 'thesis6f' for s, _, _ in data):     # the thesis' own tables, numbers from the saved thesis results
        table_thesis_layout(data, 'thesis6f', 'TSAWVP', a.out, 'six_feature_thesis_layout.tex',
                            'Complete attribution performance using 6-feature.',
                            'tab:6features_attribution_no_hybrid_weights')
        table_thesis_layout(data, 'thesis3f', 'TSV', a.out, 'three_feature_thesis_layout.tex',
                            'Complete attribution performance using 3-feature.',
                            'tab:3features_attribution_no_hybrid_weights')
    # TTP-only EVIDENCE (run_ttp_evidence.sh): the thesis' six- and three-feature tools unchanged, their saved models,
    # the same three tests; every query keeps only its TTPs.  Captions and labels: the thesis' own.
    for src, cfg, n, fname in (('ttpev6f', 'TSAWVP', 6, 'ttp_evidence_6f_thesis_layout.tex'),
                               ('ttpev3f', 'TSV', 3, 'ttp_evidence_3f_thesis_layout.tex')):
        if any(s == src and k == cfg for s, k, _ in data):
            table_thesis_layout(
                data, src, cfg, a.out, fname, f'TTPs only complete attribution performance using {n} features.',
                f'tab:TTPs_only_{n}features_attribution_no_hybrid_weights',
                what=f'the thesis {n}-feature tool unchanged (its profiles and SAVED models, nothing retrained), the same '
                     f'three tests as Table 4.{5 if n == 6 else 6};\nevery query keeps only its TTPs (sanity check: '
                     f'the TTPs of the full profile; stress test: the TTPs of the same seeded half; CTI: the TTPs of each '
                     f'report).\nThe CTI reports without TTPs count at chance (50%) in the "all reports" row.')


if __name__ == '__main__':
    main()
