#!/usr/bin/env python3
"""
external_ttp.py -- the TTP-only tool on the external evidence of FolderForNewEvaluationAttempt (Di Tizio reports and the
Olympic Destroyer case study), next to the six- and three-feature results of that evaluation (read from its
tables/analysis_summary.json, which is not changed).

  python external_ttp.py --results ../results_mac --sets ../../inputs/external_sets.json \
         --summary ../../tables/analysis_summary.json --tool-root ../../../FinalToolsPhD_6feat --out ../tables

Di Tizio: the 73 "paired" reports, variant V1 (the report's initial-access technique only: the only variant a TTP-only
tool can use).  Metrics as in analyse_external.py: Top-k hit iff mid-rank <= k, mean rank, CTI score.
Olympic Destroyer: rank of Sandworm Team (true attacker) and Lazarus Group (planted decoy) for variants A-E, every
variant reduced to its techniques.
Hybrids: WRRF (k = 60) of the eight methods with common/protocol.py HYBRID_WEIGHTS.
"""
import os
import sys
import json
import argparse

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.dont_write_bytecode = True
from sweep_core import METHODS, TOP_K, cti_score            # noqa: E402

LABEL = {'xgboost': 'XGBoost', 'gnn': 'GNN', 'siamese': 'Siamese', 'mil': 'MIL', 'rf': 'Random Forest',
         'jaccard': 'Jaccard', 'tvd': 'TVD', 'featureMatching': 'Feature Matching',
         'hybrid_no_weights': 'Hybrid, no weights', 'hybrid_self_eval_weights': 'Hybrid, self-eval weights',
         'hybrid_CTI_boosting': 'Hybrid, CTI boosting'}
ORDER = METHODS + ['hybrid_no_weights', 'hybrid_self_eval_weights', 'hybrid_CTI_boosting']


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--results', required=True)
    ap.add_argument('--config', default='T')
    ap.add_argument('--sets', required=True)
    ap.add_argument('--summary', required=True)
    ap.add_argument('--tool-root', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    sys.path.insert(0, os.path.abspath(a.tool_root))
    from common import protocol as P
    with open(a.sets) as fh:
        ext = json.load(fh)
    names = ext['apt_names']
    idx = {n: i for i, n in enumerate(names)}
    ranks = {}
    for m in METHODS:
        p = os.path.join(a.results, 'ranks_external', m, f'{a.config}.npz')
        if os.path.exists(p):
            z = np.load(p, allow_pickle=False)
            ranks[m] = {str(s): z['ranks'][i].astype(np.float64) for i, s in enumerate(z['set_ids'])}
    if len(ranks) == len(METHODS):
        for cfg, w in P.HYBRID_WEIGHTS.items():
            fused = {}
            for sid in ranks[METHODS[0]]:
                if any(np.isnan(ranks[m][sid]).any() for m in METHODS):
                    fused[sid] = np.full(len(names), np.nan)
                    continue
                fused[sid] = P.midranks(P.wrrf_scores({m: ranks[m][sid] for m in METHODS}, w))
            ranks[f'hybrid_{cfg}'] = fused
    with open(a.summary) as fh:
        summary = json.load(fh)
    paired = [u for u in ext['units'] if u['dataset'] == 'dituzio' and 'V1' in u['sets'] and 'V2' in u['sets']]
    oly = [u for u in ext['units'] if u['dataset'] == 'olympic']
    res = {'n_paired': len(paired), 'v1': {}, 'olympic': {}}
    for m in ORDER:
        if m not in ranks:
            continue
        r = np.array([ranks[m][u['sets']['V1']][idx[u['group']]] for u in paired])
        res['v1'][m] = {f'top{k}': float(100 * np.mean(r <= k)) for k in TOP_K} | \
            {'mean_rank': float(r.mean()), 'cti': float(cti_score(r, len(names)).mean())}
        res['olympic'][m] = {u['variant']: {'Sandworm Team': float(ranks[m][u['sets']['case']][idx['Sandworm Team']]),
                                            'Lazarus Group': float(ranks[m][u['sets']['case']][idx['Lazarus Group']])}
                             for u in oly}
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, 'external_ttp_only.json'), 'w') as fh:
        json.dump(res, fh, indent=1)
    # ---- table: V1 paired, TTP-only next to 3f and 6f (from the external evaluation's summary)
    lines = ['% generated by external_ttp.py -- do not edit by hand',
             f'% Di Tizio paired reports (n = {len(paired)}), V1 = initial-access technique only. TTP = TTP-only tool;',
             '% 3f / 6f = the thesis tools, read from FolderForNewEvaluationAttempt/tables/analysis_summary.json.',
             '\\begin{tabular}{l|ccc|ccc}', '\\hline',
             ' & \\multicolumn{3}{c|}{CTI score} & \\multicolumn{3}{c}{Top-20 (\\%)} \\\\',
             'Method & TTP & 3f & 6f & TTP & 3f & 6f \\\\', '\\hline']
    for m in ORDER:
        if m not in res['v1']:
            continue
        t = res['v1'][m]
        s3 = summary['tools']['3feat']['paired'].get(m, {}).get('V1', {})
        s6 = summary['tools']['6feat']['paired'].get(m, {}).get('V1', {})
        f = lambda v: '--' if v is None else f'{v:.1f}'
        if m == 'hybrid_no_weights':
            lines.append('\\hline')
        lines.append(f"{LABEL[m]} & {f(t['cti'])} & {f(s3.get('cti'))} & {f(s6.get('cti'))} & "
                     f"{f(t['top20'])} & {f(s3.get('top20'))} & {f(s6.get('top20'))} \\\\")
    lines += ['\\hline', '\\end{tabular}']
    with open(os.path.join(a.out, 'ext_v1_ttp_vs_3f_6f.tex'), 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    # ---- table: Olympic Destroyer, rank of Sandworm / Lazarus
    variants = [u['variant'] for u in oly]
    lines = ['% generated by external_ttp.py -- do not edit by hand',
             '% Olympic Destroyer, TTP-only tool: rank of Sandworm Team (true attacker) / Lazarus Group (decoy), every',
             '% variant reduced to its techniques (C and D lose their software items, so both equal B in this tool).',
             '\\begin{tabular}{l|' + 'c' * len(variants) + '}', '\\hline',
             'Method & ' + ' & '.join(v.split('_')[0] for v in variants) + ' \\\\', '\\hline']
    for m in ORDER:
        if m not in res['olympic']:
            continue
        if m == 'hybrid_no_weights':
            lines.append('\\hline')
        cells = [f"{res['olympic'][m][v]['Sandworm Team']:g} / {res['olympic'][m][v]['Lazarus Group']:g}" for v in variants]
        lines.append(f"{LABEL[m]} & " + ' & '.join(cells) + ' \\\\')
    lines += ['\\hline', '\\end{tabular}']
    with open(os.path.join(a.out, 'ext_olympic_ttp_only.tex'), 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    print(f"[external] {len(res['v1'])} methods: tables/ext_v1_ttp_vs_3f_6f.tex, ext_olympic_ttp_only.tex, external_ttp_only.json")
    for m in ORDER:
        if m in res['v1']:
            s6 = summary['tools']['6feat']['paired'].get(m, {}).get('V1', {})
            print(f"  {m:26s} V1 CTI TTP {res['v1'][m]['cti']:6.2f} | 6f {s6.get('cti', float('nan')):6.2f}")


if __name__ == '__main__':
    main()
