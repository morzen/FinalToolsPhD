#!/usr/bin/env python3
"""
make_results_md.py -- RESULTS.md (results in brief) for the feature-combination sweep.  Every number in it is read
from tables/sweep_metrics.csv, tables/external_ttp_only.json and the validation files; nothing is typed.

  python make_results_md.py --root ..        (the sweep folder)
"""
import os
import csv
import json
import argparse
from collections import defaultdict

import numpy as np

FAMILIES = ['techniques', 'software', 'capec', 'cwe', 'cve', 'pulse']
FAM_LABEL = {'techniques': 'TTPs', 'software': 'Software', 'capec': 'CAPEC', 'cwe': 'CWE', 'cve': 'CVE', 'pulse': 'Pulse'}
LETTER = {'techniques': 'T', 'software': 'S', 'capec': 'A', 'cwe': 'W', 'cve': 'V', 'pulse': 'P'}
LABEL = {'xgboost': 'XGBoost', 'gnn': 'GNN', 'siamese': 'Siamese', 'mil': 'MIL', 'rf': 'Random Forest',
         'jaccard': 'Jaccard', 'tvd': 'TVD', 'featureMatching': 'Feature Matching',
         'hybrid_no_weights': 'Hybrid (no weights)', 'hybrid_self_eval_weights': 'Hybrid (self-eval weights)',
         'hybrid_CTI_boosting': 'Hybrid (CTI boosting)'}
ORDER = ['xgboost', 'gnn', 'siamese', 'mil', 'rf', 'jaccard', 'tvd', 'featureMatching',
         'hybrid_no_weights', 'hybrid_self_eval_weights', 'hybrid_CTI_boosting']
FOUR = ['jaccard', 'featureMatching', 'tvd', 'rf']


def read(path):
    data = defaultdict(dict)
    with open(path) as fh:
        for r in csv.DictReader(fh):
            for k in ('top1', 'top5', 'top10', 'top20', 'mean_rank', 'cti_score'):
                r[k] = float(r[k]) if r.get(k) not in (None, '', 'None') else np.nan
            data[(r['source'], r['config'], r['method'])][r['evaluation']] = r
    return data


def v(data, src, cfg, m, ev, field):
    r = data.get((src, cfg, m), {}).get(ev)
    return np.nan if r is None else r[field]


def f1(x):
    return '–' if x is None or np.isnan(x) else f'{x:.1f}'


def f2(x):
    return '–' if x is None or np.isnan(x) else f'{x:.2f}'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
    ap.add_argument('--sweep-source', default='sweep')
    ap.add_argument('--ttp-source', default='mac')
    a = ap.parse_args()
    root = os.path.abspath(a.root)
    data = read(os.path.join(root, 'tables', 'sweep_metrics.csv'))

    def _n(ev, default):                 # number of queries behind an evaluation, read from the metrics (not fixed):
        ns = [int(float(r[ev]['n'])) for r in data.values()               # the largest n, because a combination without
              if ev in r and r[ev].get('n') not in (None, '', 'None')]    # TTPs has no TTP report (its row says 0)
        return max(ns) if ns else default
    NG, NR, NT = _n('sanity', 163), _n('cti30', 29), _n('cti_ttp', 27)     # groups, CTI reports, reports with TTPs
    S = a.sweep_source if any(s == a.sweep_source for s, _, _ in data) else 'cloud'
    has_mac = any(s == a.ttp_source and k == 'T' for s, k, _ in data)
    T = a.ttp_source if has_mac else S
    L = []
    w = L.append
    w('# Feature-combination sweep and TTP-only comparison: results in brief')
    w('')
    w('Generated by `code/make_results_md.py`; every number below is read from `tables/sweep_metrics.csv` (and, for '
      'section 4, `tables/external_ttp_only.json`). Design, checks and how to run: `README.md`.')
    w('')
    w('Metrics are the thesis\' own: Top-k = share of queries whose true group has mid-rank <= k (what '
      f'`evaluate_attribution` prints as precision); CTI score = 100 (1 - (rank - 1) / {NG - 1}). **Sanity** = each of '
      f'the {NG} groups queried with its full profile; **stress** = with the seeded half of each feature type; '
      f'**CTI (TTP reports)** = the {NT} of the {NR} CTI reports that contain TTPs (the same reports for every tool that has TTPs).')
    w('')
    # ------------------------------------------------------------------ 1. TTP-only evidence, thesis tools unchanged
    ev_tools = [(n, src, base, cfg) for n, src, base, cfg in ((6, 'ttpev6f', 'thesis6f', 'TSAWVP'),
                                                               (3, 'ttpev3f', 'thesis3f', 'TSV'))
                if any(s == src for s, _, _ in data)]
    w('## 1. TTP-only evidence: the thesis tools unchanged, every query restricted to its TTPs')
    w('')
    if not ev_tools:
        w('*Not run yet: `bash run_ttp_evidence.sh`.*')
        w('')
    else:
        w('The six- and three-feature tools exactly as in Tables 4.5 and 4.6 (their profiles and saved models; nothing '
          'retrained) and the same three tests; the only change is that every query keeps only its TTPs: the TTPs of '
          'the full profile (sanity check), the TTPs of the same seeded half (stress test; the half is the one of '
          'Tables 4.5 / 4.6) and the TTPs of each CTI report. Tables in the thesis layout: '
          '`tables/ttp_evidence_6f_thesis_layout.tex`, `tables/ttp_evidence_3f_thesis_layout.tex`. '
          'Each cell: all evidence (thesis table) → TTPs only.')
        w('')
        for n, src, base, cfg in ev_tools:
            w(f'**{n}-feature tool** (all evidence = Table 4.{5 if n == 6 else 6}):')
            w('')
            w('| Method | Sanity Top-1 | Stress Top-1 | Stress Top-5 | CTI (TTP reports) | CTI (all reports) |')
            w('|---|---|---|---|---|---|')
            for m in ORDER:
                if (src, cfg, m) not in data:
                    continue
                cells = []
                for ev, field, fmt in (('sanity', 'top1', f1), ('stress', 'top1', f1), ('stress', 'top5', f1),
                                       ('cti_ttp', 'cti_score', f2), ('cti30', 'cti_score', f2)):
                    cells.append(f'{fmt(v(data, base, cfg, m, ev, field))} → {fmt(v(data, src, cfg, m, ev, field))}')
                w(f'| {LABEL[m]} | ' + ' | '.join(cells) + ' |')
            w('')
        evs = (('sanity', 'top1'), ('sanity', 'top5'), ('sanity', 'top10'), ('sanity', 'top20'), ('stress', 'top1'),
               ('stress', 'top5'), ('stress', 'top10'), ('stress', 'top20'), ('cti_ttp', 'cti_score'),
               ('cti30', 'cti_score'))

        def same_values(s1, k1, s2, k2, m):
            a_ = [v(data, s1, k1, m, ev, f) for ev, f in evs]
            b_ = [v(data, s2, k2, m, ev, f) for ev, f in evs]
            return not any(np.isnan(a_)) and a_ == b_
        sets = ['jaccard', 'featureMatching', 'tvd']
        if len(ev_tools) == 2:
            same63 = [m for m in sets if same_values('ttpev6f', 'TSAWVP', 'ttpev3f', 'TSV', m)]
            same_t = [m for m in same63 if same_values('ttpev6f', 'TSAWVP', T, 'T', m)]
            learned = [m for m in ORDER[:5] if (('ttpev6f', 'TSAWVP', m) in data and ('ttpev3f', 'TSV', m) in data)]
            w(f'* Jaccard, Feature Matching and TVD compare only the feature types present in the query, so with TTP-only '
              f'queries the two tools give them the same values ({len(same63)} of 3 identical in every Top-k and CTI '
              f'value' + (f'; also identical to the TTP-only tool of section 2 for {len(same_t)} of 3' if same_t else '')
              + '). The two tools differ only through the trained models' + (
                  ': ' + ', '.join(f"{LABEL[m]} stress Top-1 {f1(v(data, 'ttpev6f', 'TSAWVP', m, 'stress', 'top1'))} "
                                   f"(6f) / {f1(v(data, 'ttpev3f', 'TSV', m, 'stress', 'top1'))} (3f)" for m in learned)
                  if learned else '') + '.')
        n_empty = next((r['sanity']['n_groups_empty'] for (s, k, m), r in data.items() if s == S and k == 'T'
                        and 'sanity' in r and r['sanity'].get('n_groups_empty') not in (None, '')), '')
        if n_empty != '':
            w(f'* {n_empty} of the {NG} groups have no TTP: their TTP-only query is empty, so the sanity-check Top-1 of '
              f'most methods stops at {100 * (NG - int(n_empty)) / NG:.2f}%.')
        w(f'* CTI: {NR - NT} of the {NR} reports list no TTP. With TTP-only queries they cannot be scored and count at chance '
          f'(50%) in the {NR}-report row, as in the TTP-only rows of section 2; the {NT}-report row leaves them out.')
        w('')
    # ------------------------------------------------------------------ 2. TTP-only tool vs 3f vs 6f
    w('## 2. TTP-only tool (retrained on TTPs only) against the thesis tools')
    w('')
    w('Here the *tool* is TTP-only: every non-TTP feature type blanked in the data and the models retrained on it (the '
      'T combination of the sweep in section 3). This is not the experiment of section 1, where the thesis tools and '
      'their models are unchanged and only the queries are restricted.')
    w('')
    if not has_mac:
        w('*The Mac run (XGBoost, GNN, Siamese, MIL retrained TTP-only) is not in yet: only the four methods run in '
          'the cloud are filled in.*')
        w('')
    w('| Method | Sanity Top-1 TTP / 3f / 6f | Stress Top-1 TTP / 3f / 6f | Stress Top-5 TTP / 3f / 6f | CTI (TTP reports) TTP / 3f / 6f |')
    w('|---|---|---|---|---|')
    for m in ORDER:
        if (T, 'T', m) not in data and ('thesis6f', 'TSAWVP', m) not in data:
            continue
        cells = []
        for ev, field, fmt in (('sanity', 'top1', f1), ('stress', 'top1', f1), ('stress', 'top5', f1), ('cti_ttp', 'cti_score', f2)):
            cells.append(' / '.join(fmt(v(data, src, cfg, m, ev, field))
                                    for src, cfg in ((T, 'T'), ('thesis3f', 'TSV'), ('thesis6f', 'TSAWVP'))))
        w(f'| {LABEL[m]} | ' + ' | '.join(cells) + ' |')
    w('')
    n_empty_T = next((r['sanity']['n_groups_empty'] for (s, k, m), r in data.items() if s == S and k == 'T' and 'sanity' in r), '')
    have = [m for m in ORDER if not np.isnan(v(data, T, 'T', m, 'stress', 'top1'))]
    lower = [m for m in have if v(data, T, 'T', m, 'stress', 'top1') < v(data, 'thesis6f', 'TSAWVP', m, 'stress', 'top1')]

    def deltas(ev, field, ms, nd):
        return ', '.join(f"{LABEL[m]} {v(data, T, 'T', m, ev, field) - v(data, 'thesis6f', 'TSAWVP', m, ev, field):+.{nd}f}"
                         for m in ms)
    w(f'* **Self-evaluation (sanity check, stress test).** On the stress test TTP-only is below the six-feature tool for '
      f'{len(lower)} of the {len(have)} methods and hybrids'
      + (f' (not for {", ".join(LABEL[m] for m in have if m not in lower)})' if len(lower) < len(have) else '') +
      '. Difference TTP-only minus six-feature, stress-test Top-1 (points): ' + deltas('stress', 'top1', have, 1) + '. '
      f'{n_empty_T} of the {NG} groups have no technique at all. An empty query cannot single one of them out, so the '
      f'sanity-check Top-1 of most methods stops at {100 * (NG - int(n_empty_T)) / NG:.1f}%; a model can still put one '
      'of them first by its own preference for an empty input (XGBoost does).')
    learned = [m for m in have if m not in ('jaccard', 'tvd', 'featureMatching')]
    w(f'* **CTI reports (the {NT} with TTPs).** Difference TTP-only minus six-feature, CTI score (points): '
      + deltas('cti_ttp', 'cti_score', learned, 2) + '. '
      'Jaccard, Feature Matching and TVD compare only the feature types present in the evidence, so TTP-only and '
      'six-feature give them the same rank on every report that holds only TTPs (25 of the ' + str(NT) + '). Their differences ('
      + deltas('cti_ttp', 'cti_score', [m for m in have if m in ('jaccard', 'tvd', 'featureMatching')], 2) +
      ') come from the 2 reports that also list software.')
    w('')
    # ------------------------------------------------------------------ 2b. retraining spread
    mac = sorted({s for s, _, _ in data if s == a.ttp_source or s.startswith(a.ttp_source + '_r')})
    reps = [s for s in mac if s != T and any(k == 'T' for s2, k, _ in data if s2 == s)]
    six_runs = ['thesis6f'] + [s for s in mac if any(k == 'TSAWVP' for s2, k, _ in data if s2 == s)]
    if reps or len(six_runs) > 1:
        runs = [T] + reps
        w(f'### Retraining: {len(runs)} trainings of the TTP-only tool, {len(six_runs)} of the six-feature tool')
        w('')
        w('GNN, Siamese and MIL are trained without a fixed seed (Siamese fixes only its train / validation split), so '
          'every training gives a different model. XGBoost and the Random Forest fix `random_state = 42`; the three '
          'set-based measures are not trained. TTP-only runs: run 1 is the one in the table above. ' +
          (f'Six-feature runs: your thesis model first, then {len(six_runs) - 1} retraining'
           f'{"s" if len(six_runs) > 2 else ""} with the same code and data (`CONFIGS=6f REPEATS=n bash run_neural_sweep.sh`).'
           if len(six_runs) > 1 else 'Six-feature: your thesis model (not retrained).'))
        w('')
        w('| Method | Stress Top-1, TTP-only runs | Stress Top-1, 6f runs | CTI (TTP reports), TTP-only runs | CTI (TTP reports), 6f runs '
          '| CTI (TTP reports) mean, TTP-only / 6f | pairs of trainings with TTP-only below 6f on CTI (TTP reports) |')
        w('|---|---|---|---|---|---|---|')

        def below_pairs(a_t, a_6):
            return sum(x < y for x in a_t for y in a_6), len(a_t) * len(a_6)

        stress_all_below = []
        for m in ORDER:
            st_t = [v(data, s, 'T', m, 'stress', 'top1') for s in runs]
            ct_t = [v(data, s, 'T', m, 'cti_ttp', 'cti_score') for s in runs]
            st_6 = [v(data, s, 'TSAWVP', m, 'stress', 'top1') for s in six_runs]
            ct_6 = [v(data, s, 'TSAWVP', m, 'cti_ttp', 'cti_score') for s in six_runs]
            if all(np.isnan(x) for x in st_t):
                continue
            a_t = [x for x in ct_t if not np.isnan(x)]
            a_6 = [x for x in ct_6 if not np.isnan(x)]
            k, n = below_pairs(a_t, a_6)
            verdict = '–' if not n else ('all' if k == n else ('none' if k == 0 else 'some')) + f' ({k} of {n})'
            ks, ns = below_pairs([x for x in st_t if not np.isnan(x)], [x for x in st_6 if not np.isnan(x)])
            if ns and ks == ns:
                stress_all_below.append(m)
            w(f"| {LABEL[m]} | {' / '.join(f1(x) for x in st_t)} | {' / '.join(f1(x) for x in st_6)} | "
              f"{' / '.join(f2(x) for x in ct_t)} | {' / '.join(f2(x) for x in ct_6)} | "
              f"{f2(np.mean(a_t)) if a_t else '–'} / {f2(np.mean(a_6)) if a_6 else '–'} | {verdict} |")
        w('')
        n_shown = len([m for m in ORDER if not all(np.isnan(v(data, s, 'T', m, 'stress', 'top1')) for s in runs)])
        w(f'Stress test: TTP-only is below the six-feature tool in every pair of trainings for {len(stress_all_below)} of '
          f'the {n_shown} methods and hybrids'
          + (f' (not for {", ".join(LABEL[m] for m in ORDER if m not in stress_all_below and not all(np.isnan(v(data, s, "T", m, "stress", "top1")) for s in runs))})'
             if len(stress_all_below) < n_shown else '') + '.')
        w('')
        if len(six_runs) > 1:
            same = [m for m in ('xgboost', 'rf') if all(
                v(data, s, 'TSAWVP', m, ev, fld) == v(data, 'thesis6f', 'TSAWVP', m, ev, fld)
                for s in six_runs[1:] for ev, fld in (('sanity', 'top1'), ('stress', 'top1'), ('stress', 'top5'),
                                                      ('cti_ttp', 'cti_score'), ('cti30', 'cti_score')))]
            w('Retrained six-feature models that give exactly the thesis values (sanity, stress Top-1 / Top-5, both CTI '
              'scores): ' + (', '.join(LABEL[m] for m in same) if same else 'none') + '. '
              'The three-feature values are the thesis models only (not retrained).')
        else:
            w('The six-feature and three-feature values are single trainings (the thesis models). '
              '`CONFIGS=6f REPEATS=2 bash run_neural_sweep.sh` retrains the six-feature tool twice (about 2 h).')
        w('')
    # ------------------------------------------------------------------ 3. sweep
    rf_mac = os.path.join(root, 'results_mac_rf', 'validation.json')
    sweep_meths = [m for m in ORDER if any(s == S and mm == m for s, _, mm in data)]
    n_done = {m: len({k for (s, k, mm), r in data.items() if s == S and mm == m and 'stress' in r}) for m in sweep_meths}
    w('## 3. All 63 combinations')
    w('')
    w('Figures: `figures/sweep_all_in_one.pdf` (everything in one graph: stress test Top-1, the eight approaches and '
      'the three hybrid weightings; `_sanity`, `_cti`), `figures/sweep_precision_by_size.pdf` (stress test Top-1, '
      'the eight approaches), `_sanity_top1`, '
      '`_stress_top5`, `_cti`, `_hybrids`; `figures/sweep_family_effect.pdf` (and `_hybrids`); '
      '`figures/sweep_overview.pdf` (every combination x approach: stress test Top-1), `sweep_overview_sanity.pdf`, '
      '`sweep_overview_cti.pdf`. Tables: `tables/sweep_all_combinations.tex`, `sweep_all_combinations_cti.tex`, '
      '`tables/sweep_family_effect.tex`.')
    w('')
    missing = [m for m in sweep_meths if n_done[m] < 63]
    w('One result per combination and approach. Jaccard, Feature Matching and TVD need no training and give your saved '
      '6f / 3f results exactly. ' +
      ('The Random Forest is retrained for every combination with your venv (`run_rf_sweep_mac.sh`); in the 6f and 3f '
       'combinations it gives your saved RF results exactly (section 5). '
       if os.path.exists(os.path.join(root, 'results_mac_rf', 'validation.json')) else
       'The Random Forest is retrained for every combination in the cloud (section 5). '
       if os.path.isdir(os.path.join(root, 'results_cloud')) else
       'The Random Forest is retrained for every combination on your Mac in the same run as the other models. ') +
      'XGBoost, GNN, Siamese and MIL are trained once per combination on your Mac (`CONFIGS=all bash '
      'run_neural_sweep.sh`); for 6f this is the first retraining, not your thesis model (section 2). The hybrids are '
      'computed wherever all eight approaches are done.' +
      (' Not all combinations are done yet: ' + ', '.join(f'{LABEL[m]} {n_done[m]} of 63' for m in missing) + '.'
       if missing else ''))
    w('')
    w('| Approach | combinations | Stress Top-1: TTP-only | 3f | 6f | lowest / highest | of those with TTPs | '
      'best combination |')
    w('|---|---|---|---|---|---|---|---|')
    for m in sweep_meths:
        vals = [(k, r['stress']['top1']) for (s, k, mm), r in data.items() if s == S and mm == m and 'stress' in r]
        wt = [x for k, x in vals if 'T' in k]
        best = max(vals, key=lambda kv: kv[1])
        bests = [k for k, x in vals if x == best[1]]
        w(f'| {LABEL[m]} | {n_done[m]} | {f1(v(data, S, "T", m, "stress", "top1"))} | '
          f'{f1(v(data, S, "TSV", m, "stress", "top1"))} | {f1(v(data, S, "TSAWVP", m, "stress", "top1"))} | '
          f'{min(x for _, x in vals):.1f} / {max(x for _, x in vals):.1f} | '
          f'{(f"{min(wt):.1f} / {max(wt):.1f}" if wt else "–")} | {", ".join(sorted(bests, key=len))} ({best[1]:.1f}) |')
    w('')
    # mean by number of feature types
    w('Mean stress-test Top-1 of the combinations with 1 to 6 feature types:')
    w('')
    w('| Approach | 1 | 2 | 3 | 4 | 5 | 6 |')
    w('|---|---|---|---|---|---|---|')
    for m in sweep_meths:
        by = {}
        for (s, k, mm), r in data.items():
            if s == S and mm == m and 'stress' in r and not np.isnan(r['stress']['top1']):
                by.setdefault(len(k), []).append(r['stress']['top1'])
        w(f'| {LABEL[m]} | ' + ' | '.join((f'{np.mean(by[n]):.1f}' + ('' if len(by[n]) == [6, 15, 20, 15, 6, 1][n - 1]
                                                                     else f' ({len(by[n])})')) if n in by else '–'
                                          for n in range(1, 7)) + ' |')
    w('')
    # family effects
    w('Median change of the stress-test Top-1 (percentage points) when a feature type is added to a combination that '
      'lacks it (31 pairs per type when every combination is done; minimum and maximum in '
      '`tables/sweep_family_effect.tex`):')
    w('')
    w('| Approach | ' + ' | '.join(FAM_LABEL[f] for f in FAMILIES) + ' |')
    w('|---|' + '---|' * len(FAMILIES))
    for m in sweep_meths:
        vals = {k: r['stress']['top1'] for (s, k, mm), r in data.items() if s == S and mm == m and 'stress' in r}
        cells = []
        for f in FAMILIES:
            d = [vals[plus] - x for k, x in vals.items() if LETTER[f] not in k
                 for plus in [''.join(c for c in 'TSAWVP' if c in k + LETTER[f])] if plus in vals]
            cells.append(f'{np.median(d):+.1f}' + ('' if len(d) == 31 else f' (n={len(d)})') if d else '–')
        w(f'| {LABEL[m]} | ' + ' | '.join(cells) + ' |')
    w('')
    ctis = {m: [r['cti_ttp']['cti_score'] for (s, k, mm), r in data.items() if s == S and mm == m and 'T' in k
                and 'cti_ttp' in r and not np.isnan(r['cti_ttp']['cti_score'])] for m in sweep_meths}
    w('CTI score on the TTP reports, over the combinations that contain TTPs (32 when all are done): ' +
      '; '.join(f'{LABEL[m]} {min(x):.2f} to {max(x):.2f}' + ('' if len(x) == 32 else f' ({len(x)} combinations)')
                for m, x in ctis.items() if x) + '.')
    w('')
    # ------------------------------------------------------------------ 4. external
    ext_p = os.path.join(root, 'tables', 'external_ttp_only.json')
    if os.path.exists(ext_p):
        with open(ext_p) as fh:
            ext = json.load(fh)
        w('## 4. External evidence, TTP-only tool')
        w('')
        w(f'Di Tizio paired reports (n = {ext["n_paired"]}), V1 = the report\'s initial-access technique only: '
          '`tables/ext_v1_ttp_vs_3f_6f.tex` (with the 3f / 6f values of the external evaluation). Olympic Destroyer, '
          'rank of Sandworm Team / Lazarus Group: `tables/ext_olympic_ttp_only.tex`.')
        w('')
        w('| Method | V1 CTI score (TTP-only) | V1 Top-20 (%) | Olympic B: Sandworm / Lazarus rank |')
        w('|---|---|---|---|')
        for m in ORDER:
            if m in ext['v1']:
                ob = ext['olympic'][m].get('B_full_behaviour', {})
                w(f"| {LABEL[m]} | {ext['v1'][m]['cti']:.2f} | {ext['v1'][m]['top20']:.1f} | "
                  f"{ob.get('Sandworm Team', float('nan')):g} / {ob.get('Lazarus Group', float('nan')):g} |")
        w('')
    # ------------------------------------------------------------------ 5. checks and limits
    w('## 5. Checks')
    w('')
